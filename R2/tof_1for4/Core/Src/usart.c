/**
 * @brief  DMA发送完成回调
 *         清除uart1_tx_busy标志, 允许下一次DMA发送
 */
void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        uart1_tx_busy = 0;
    }
}

/**
 * @brief  printf重定向fputc (USART1阻塞发送)
 */
int fputc(int ch, FILE *f)
{
    HAL_UART_Transmit(&huart1, (uint8_t *)&ch, 1, 100);
    return ch;
}

/**
 * @brief  阻塞式调试输出 (USART1)
 *         不影响FreeRTOS调度, 简单可靠
 */
void debug_printf(const char *fmt, ...)
{
    va_list args;
    va_start(args, fmt);
    int len = vsnprintf((char *)g_usart1_tx_buf, sizeof(g_usart1_tx_buf), fmt, args);
    va_end(args);

    if (len > 0)
    {
        HAL_UART_Transmit(&huart1, g_usart1_tx_buf, (uint16_t)len, 200);
    }
}

